"""Reversible additive SII patches for missing keyboard bindings."""
import re

CHORD = 'keyboard.rctrl?0 & keyboard.rshift?0'
LEGACY_CHORD = 'keyboard.lctrl?0 & keyboard.lalt?0'


def patch_controls(text: str, bindings: dict) -> str:
    if len(set(bindings.values())) != len(bindings):
        raise ValueError('Duplicate new base keys')
    for action, key in bindings.items():
        if not re.fullmatch(r'f(?:[1-9]|1[0-2])', key):
            raise ValueError('Only F1-F12 chord keys supported')
        if not re.search(r'"mix ' + re.escape(action) + r' `[^`]*`"', text):
            raise ValueError(f'Game action missing: {action}')
    # Migrate only exact expressions generated by v1, including base-key guards.
    # Do not touch the user's standalone left Ctrl / controller gear bindings.
    text = text.replace(LEGACY_CHORD, CHORD)
    pending = {}
    for action, key in bindings.items():
        expression = re.search(r'"mix ' + re.escape(action) + r' `([^`]*)`"', text)[1]
        if f'({CHORD} & keyboard.{key}?0)' not in expression:
            pending[action] = key
    for key in set(pending.values()):
        if f'(keyboard.{key}?0 & !({CHORD}))' in text:
            continue
        text = re.sub(r'keyboard\.' + key + r'\?0\b',
                      lambda m: f'({m.group()} & !({CHORD}))', text)
    for action, key in pending.items():
        pattern = r'("mix ' + re.escape(action) + r' `)([^`]*)(`")'
        text, n = re.subn(pattern, lambda m: m[1] + f'({CHORD} & keyboard.{key}?0) | (' + m[2] + ')' + m[3], text)
        if n != 1:
            raise ValueError(f'Expected one mix for {action}, got {n}')
    return text
